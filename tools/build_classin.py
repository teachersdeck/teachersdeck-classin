#!/usr/bin/env python3
"""Build the hosted ClassIn web edition of TeachersDeck.

    python3 tools/build_classin.py            ->  build/classin-site/   and   dist/teachersdeck-classin-site-<version>-<build>.zip

What it does
  * copies the web files (not the Chrome-extension files: manifest.json, mic.html, the extension changelogs)
  * bakes <meta name="td-edition" content="classin"> into index.html, so the hosted site IS the ClassIn edition with no URL parameter
  * writes _redirects (short links such as /t5), _headers, robots.txt and build-info.json
  * writes classin/LESSON-TEMPLATES.md from classin/packs.json
  * CHECKS the result and exits non-zero if something is wrong: every local file the pages refer to exists, every widget id in packs.json is a real widget,
    every short link is well-formed, the JSON parses.
The same source tree still builds the Chrome extension unchanged (the ClassIn files are inert there)."""
import json, os, re, shutil, sys, zipfile, datetime, urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'build', 'classin-site'); DIST = os.path.join(ROOT, 'dist')
BUILD = 'classin.1'
INCLUDE = ['index.html', 'manual.html', 'classin-check.html', 'classin-links.html', 'classin-guide.html', 'css', 'js', 'games', 'icons', 'classin']
SKIP_NAMES = {'.DS_Store'}
problems = []

def read(p):
    with open(p, encoding='utf-8') as f: return f.read()

def main():
    app = read(os.path.join(ROOT, 'js', 'app.js'))
    version = re.search(r"APP_VERSION\s*=\s*'([^']+)'", app).group(1)
    widget_ids = set(re.findall(r"\{ id:'(\w+)', cat:'\w+'", app))
    packs = json.load(open(os.path.join(ROOT, 'classin', 'packs.json'), encoding='utf-8'))

    if os.path.isdir(OUT): shutil.rmtree(OUT)
    os.makedirs(OUT)
    for name in INCLUDE:
        src = os.path.join(ROOT, name)
        if not os.path.exists(src): problems.append(f'missing source: {name}'); continue
        dst = os.path.join(OUT, name)
        if os.path.isdir(src): shutil.copytree(src, dst, ignore=shutil.ignore_patterns(*SKIP_NAMES, 'LESSON-TEMPLATES.md', 'PORT-STATUS.md', 'DEPLOY.md', 'TEST-REPORT-TEMPLATE.md', 'VIDEO-SCRIPTS.md') if name == 'classin' else shutil.ignore_patterns(*SKIP_NAMES))
        else: shutil.copy2(src, dst)

    # 1. the hosted site IS the ClassIn edition
    idx = os.path.join(OUT, 'index.html'); h = read(idx)
    if 'name="td-edition"' not in h:
        h = h.replace('<head>', '<head>\n<meta name="td-edition" content="classin">', 1)
    open(idx, 'w', encoding='utf-8').write(h)

    # 2. short links -> _redirects (302 so the full link shows in the address bar and can be edited)
    lines = ['# Short links for the ClassIn edition. Generated by tools/build_classin.py from classin/packs.json — do not edit by hand.']
    seen = set()
    for s in packs['shortlinks']:
        slug = s['slug']
        if not re.fullmatch(r'[a-z0-9-]{1,24}', slug): problems.append(f'bad slug {slug!r}'); continue
        if slug in seen: problems.append(f'duplicate slug {slug!r}'); continue
        seen.add(slug)
        if s['w'] and s['w'] not in widget_ids: problems.append(f'short link /{slug}: unknown widget {s["w"]!r}')
        q = [('edition', 'classin')] + ([('w', s['w'])] if s['w'] else []) + list(s['params'].items())
        qs = '&'.join(k + '=' + urllib.parse.quote(v, safe="~,|") for k, v in q)
        lines.append(f'/{slug}  /index.html?{qs}  302')
    open(os.path.join(OUT, '_redirects'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

    # 3. headers + robots + build info
    open(os.path.join(OUT, '_headers'), 'w', encoding='utf-8').write(
"""/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: microphone=(self), camera=(), geolocation=()
/index.html
  Cache-Control: no-cache
/classin-*.html
  Cache-Control: no-cache
/css/*
  Cache-Control: public, max-age=3600
/js/*
  Cache-Control: public, max-age=3600
/icons/*
  Cache-Control: public, max-age=86400
""")
    open(os.path.join(OUT, 'robots.txt'), 'w', encoding='utf-8').write('User-agent: *\nAllow: /\n')
    info = {'app_version': version, 'classin_build': BUILD, 'built': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'), 'widgets': len(widget_ids)}
    open(os.path.join(OUT, 'build-info.json'), 'w', encoding='utf-8').write(json.dumps(info, indent=1))

    # 4. LESSON-TEMPLATES.md from the packs (also kept in the source tree, for the docs)
    md = ['# ClassIn lesson templates', '', 'Generated from `classin/packs.json` by `tools/build_classin.py`. Replace `https://YOUR-SITE` with your address (or use the **Lesson packs** section of `classin-links.html`, which does it for you).',
          'Vietnamese text needs a native-speaker check before it is shown to customers.', '']
    for pk in packs['packs']:
        md += [f"## {pk['title']['en']} · {pk['title']['vi']}", f"*{pk['when']['en']}* · *{pk['when']['vi']}*", '']
        for l in pk['links']:
            if l['w'] not in widget_ids: problems.append(f"pack {pk['id']}: unknown widget {l['w']!r}")
            qs = '&'.join(k + '=' + urllib.parse.quote(v, safe="~,|") for k, v in [('edition', 'classin'), ('w', l['w'])] + list(l['params'].items()))
            md.append(f"- **{l['label']['en']}** / {l['label']['vi']}  \n  `https://YOUR-SITE/index.html?{qs}`")
        md.append('')
    text = '\n'.join(md)
    open(os.path.join(ROOT, 'classin', 'LESSON-TEMPLATES.md'), 'w', encoding='utf-8').write(text)
    open(os.path.join(OUT, 'classin', 'LESSON-TEMPLATES.md'), 'w', encoding='utf-8').write(text)

    # 5. checks: every local file the pages refer to exists
    for page in ['index.html', 'classin-check.html', 'classin-links.html', 'classin-guide.html']:
        body = read(os.path.join(OUT, page))
        for m in re.finditer(r'(?:src|href)="([^"#?:]+?\.(?:js|css|png|svg|html|json|ico))(?:\?[^"]*)?"', body):
            ref = m.group(1)
            if ref.startswith(('http', '//')): continue
            if not os.path.exists(os.path.join(OUT, ref)): problems.append(f'{page}: refers to missing file {ref}')
    for must in ['js/edition.js', 'js/classin.js', 'css/classin.css', 'js/app.js', 'js/qrcode-lib.js']:
        if not os.path.exists(os.path.join(OUT, must)): problems.append(f'missing {must}')
    if 'js/edition.js' not in read(idx) or 'js/classin.js' not in read(idx): problems.append('index.html does not load edition.js / classin.js')
    # the extension-only files must NOT be in the hosted build
    for bad in ['manifest.json', 'mic.html']:
        if os.path.exists(os.path.join(OUT, bad)): problems.append(f'extension-only file leaked into the web build: {bad}')

    # 6. zip
    os.makedirs(DIST, exist_ok=True)
    zpath = os.path.join(DIST, f'teachersdeck-classin-site-{version}-{BUILD}.zip')
    if os.path.exists(zpath): os.remove(zpath)
    with zipfile.ZipFile(zpath, 'w', zipfile.ZIP_DEFLATED) as z:
        for d, _, files in os.walk(OUT):
            for f in files:
                full = os.path.join(d, f); z.write(full, os.path.relpath(full, OUT))
    n = sum(len(f) for _, _, f in os.walk(OUT))
    print(f'built {n} files -> {os.path.relpath(OUT, ROOT)}  and  {os.path.relpath(zpath, ROOT)}')
    print(f'  version {version} · {BUILD} · {len(widget_ids)} widgets · {len(packs["shortlinks"])} short links · {sum(len(p["links"]) for p in packs["packs"])} pack links')
    if problems:
        print('\nPROBLEMS:'); [print('  - ' + p) for p in problems]; sys.exit(1)
    print('  checks passed')

if __name__ == '__main__':
    main()
